/* Portable CSV behavior, using synthetic cases only. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const core = fs.readFileSync(path.join(__dirname, '../reviews/occlusion_offline.js'), 'utf8');
const data = vm.runInNewContext(core + '\nReviewData;');
const row = id => Object.fromEntries(data.fields.map(field => [field, data.humanFields.includes(field) ? '' : field === 'annotation_id' ? id : 'fixture']));
const baseline = [row('1'), row('2'), row('3')];
const copy = value => JSON.parse(JSON.stringify(value));
const review = (rows, index, name, note = 'Synthetic fixture evidence') => Object.assign(rows[index], {level: 'low', reviewer: name, visual_evidence: note});
const roundtrip = copy(baseline);
review(roundtrip, 0, 'Fixture Á', 'Rama, "hojas"\r\nsegunda línea\n</script>');
assert.equal(JSON.stringify(data.parseCsv(data.csv(roundtrip))), JSON.stringify(roundtrip));
assert.equal(data.complete(roundtrip[0]), true);
roundtrip[0].visual_evidence = '  ';
assert.equal(data.complete(roundtrip[0]), false);
assert.throws(() => data.parseCsv(data.csv(baseline).replace('fixture,fixture', '"broken,fixture')), /CSV/);
const duplicate = copy(baseline); duplicate[1] = copy(duplicate[0]);
assert.throws(() => data.validate(duplicate, baseline), /duplicados/);
const changedWeight = copy(baseline); changedWeight[0].sample_weight = '99';
assert.throws(() => data.validate(changedWeight, baseline), /muestra/);
const invalidLevel = copy(baseline); invalidLevel[0].level = 'extreme';
assert.throws(() => data.validate(invalidLevel, baseline), /desconocido/);
const first = copy(baseline), second = copy(baseline);
review(first, 0, 'Fixture One'); review(second, 1, 'Fixture Two');
const joined = data.merge(first, second, baseline);
assert.equal(joined.changed, 1);
assert.equal(joined.rows[0].reviewer, 'Fixture One');
assert.equal(joined.rows[1].reviewer, 'Fixture Two');
assert.equal(data.merge(joined.rows, baseline, baseline).changed, 0);
assert.equal(data.merge(joined.rows, second, baseline).changed, 0);
const conflict = copy(second); review(conflict, 0, 'Fixture Three'); review(conflict, 2, 'Fixture Three');
const before = JSON.stringify(joined.rows);
assert.throws(() => data.merge(joined.rows, conflict, baseline), /revisiones diferentes/);
assert.equal(JSON.stringify(joined.rows), before);
const partial = copy(baseline); partial[0].level = 'high'; partial[0].reviewer = 'Partial fixture';
assert.throws(() => data.merge(partial, first, baseline), /revisiones diferentes/);
const resumed = data.merge(baseline, first.reverse(), baseline);
assert.equal(resumed.rows[0].annotation_id, '1');
assert.equal(resumed.rows[0].reviewer, 'Fixture One');
console.log('PASS: CSV round-trip, multiline accents, validation, resume, merge, conflicts and preservation.');
